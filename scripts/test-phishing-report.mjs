import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire(new URL('../frontend/package.json', import.meta.url));
const ts = require('typescript');
const source = readFileSync(new URL('../frontend/src/components/phishing_url/reportInsights.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { domainDifference, reportOpinion, urlReportSummary } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const diff = domainDifference('paypai.com', 'paypal.com').filter(c => c.changed);
assert.deepEqual(diff, [{ actual:'i', reference:'l', changed:true, actualPosition:6 }]);
for (const [actual, reference] of [['abxc.com','abc.com'], ['abc.com','abxc.com'], ['раypal.com','paypal.com'], ['example.com','example.com']]) {
  const cells = domainDifference(actual, reference);
  assert.equal(cells.map(c=>c.actual).join(''), actual);
  assert.equal(cells.map(c=>c.reference).join(''), reference);
}
assert.equal(domainDifference('a'.repeat(254), 'a').length, 0);
const scan = (probability, findings=[], signals={}, status='PARTIAL_SUCCESS') => ({result:{status,metadata:{assessment_policy:'dynamic-v2',link_analysis_version:'links-v1',threshold:0.7,score_components:{model_probability:probability},forensics:{findings,network:{signals}}}}});
assert.equal(reportOpinion(scan(0.2,[],{dns:{status:'observed'},tls:{status:'observed'},http:{status:'observed'}})).tone, 'positive');
assert.equal(reportOpinion(scan(0.2,[{severity:'medium'}])).tone, 'caution');
assert.equal(reportOpinion(scan(0.8)).tone, 'danger');
assert.equal(reportOpinion(scan(0.1,[{severity:'high'}])).tone, 'danger');
assert.equal(reportOpinion(scan(0.1,[],{},'UNAVAILABLE')).tone, 'neutral');
assert.equal(reportOpinion(scan(0.6)).tone, 'neutral');
const borderline = scan(0.699);
borderline.result.risk_score = 69.9;
borderline.result.metadata.branch_probabilities = {structural:0.076,url_text:0.99};
assert.match(reportOpinion(borderline).title, /Borderline/);
const summary = urlReportSummary(borderline);
assert.equal(summary.risk,69.9);
assert.equal(summary.trust,30.1);
assert.equal(summary.confidence,'Limited');
assert.match(summary.confidenceReason,/disagree/);
assert.match(summary.modelText,/borderline/);
const rescued = scan(.98);
rescued.result.metadata.threshold = .9;
rescued.result.metadata.rescue_applied = true;
rescued.result.metadata.primary_model_probability = .2;
rescued.result.metadata.primary_model_threshold = .7;
assert.match(urlReportSummary(rescued).modelText,/first URL expert was below/);
assert.match(urlReportSummary(rescued).modelText,/second expert crossed/);
assert.match(urlReportSummary(rescued).modelText,/not prediction-confidence percentages/);
assert.match(summary.cards.find(c=>c.title==='Password collection').text,/could not be assessed/);
const live = scan(0.1,[],{http:{status:'observed',status_code:200,redirects:1,final_url:'https://destination.example/login'},html:{status:'observed',password_forms:[{action:'https://identity.example/submit'}]},tls:{status:'observed',certificate:{},analysis:{issuer:'Test issuer',not_after:'2027-01-01'}},dns:{status:'observed',addresses:['8.8.8.8']}});
live.result.risk_score=10;
live.result.metadata.forensics.hostname='destination.example';
live.result.metadata.forensics.path_analysis={path:'/login',segments:1,navigation_parameters:[]};
const liveSummary=urlReportSummary(live);
assert.match(liveSummary.cards.find(c=>c.title==='Page and redirects').text,/destination.example\/login/);
assert.match(liveSummary.cards.find(c=>c.title==='Password collection').text,/identity.example\/submit/);
assert.match(liveSummary.cards.find(c=>c.title==='Connection security').text,/Test issuer/);
assert.equal(urlReportSummary(scan(0.1,[],{},'UNAVAILABLE')).trust,null);
const componentSource = readFileSync(new URL('../frontend/src/components/phishing_url/PhishingAnalysis.tsx', import.meta.url), 'utf8');
const helperUrl = `data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`;
const componentJs = ts.transpileModule(componentSource.replace("'./reportInsights'", JSON.stringify(helperUrl)), {compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText.replaceAll('"react/jsx-runtime"',JSON.stringify(pathToFileURL(require.resolve('react/jsx-runtime')).href));
const { PhishingAnalysis } = await import(`data:text/javascript;base64,${Buffer.from(componentJs).toString('base64')}`);
const { createElement } = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const html = renderToStaticMarkup(createElement(PhishingAnalysis,{scan:live}));
assert.match(html,/What we found for this URL/);
assert.match(html,/identity.example\/submit/);
assert.match(html,/Our conclusion for/);
assert.doesNotMatch(html,/Parse the submitted link and identify/);
const uncertainHtml=renderToStaticMarkup(createElement(PhishingAnalysis,{scan:borderline}));
assert.match(uncertainHtml,/borderline result/);
assert.match(uncertainHtml,/disagree substantially/);
console.log('Phishing report checks passed: domain alignment, Unicode, insertions/deletions, uncertainty and evidence leaning.');
